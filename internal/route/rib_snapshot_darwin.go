// readRoutes reads the IPv4 routing table in process, from the kernel's
// routing information base, as the RouteEntry rows `netstat -rn -f inet`
// prints: the same destination, gateway and flag spellings, so every reader of
// a snapshot sees what it saw through netstat. Reading takes well under a
// millisecond per hundred rows and does not depend on the size of any text
// the table would print, which is what the netstat runner's output cap broke
// on a table of a few thousand rows. It is read-only.
func readRoutes() ([]RouteEntry, error) {
	// The extended dump: its messages carry the flags of the route each row was
	// cloned from, which decides whether netstat shows the row.
	rib, err := xroute.FetchRIB(syscall.AF_INET, ribTypeDump2, 0)
	if err != nil {
		return nil, fmt.Errorf("fetch routing table: %w", err)
	}
	rib, err = dropProtocolClones(rib)
	if err != nil {
		return nil, err
	}
	msgs, err := xroute.ParseRIB(ribTypeDump2, rib)
	if err != nil {
		return nil, fmt.Errorf("parse routing table: %w", err)
	}
	return ribEntries(msgs, interfaceNames), nil
}

// ribTypeDump2 is NET_RT_DUMP2, the routing table dump netstat reads.
const ribTypeDump2 = xroute.RIBType(syscall.NET_RT_DUMP2)

// Offsets in the BSD rt_msghdr2 that the clone filter reads: the message
// length, the route flags after the 16-bit interface index and its padding,
// and the flags of the parent route the row was cloned from.
const (
	ribMsgLenOffset     = 0
	ribFlagsOffset      = 8
	ribParentFlagsStart = 20
	ribHeaderMin        = ribParentFlagsStart + 4
)

// dropProtocolClones removes, in place, the rows netstat leaves out unless it
// is given -a: routes generated by cloning from a parent route that has
// RTF_PRCLONING, such as the per-destination host routes the kernel creates
// under a scoped default route. They are numerous, change constantly, and no
// RouteWise decision reads them.
func dropProtocolClones(rib []byte) ([]byte, error) {
	kept := 0
	for off := 0; off < len(rib); {
		if len(rib)-off < ribHeaderMin {
			return nil, fmt.Errorf("routing table dump is truncated at byte %d", off)
		}
		n := int(binary.NativeEndian.Uint16(rib[off+ribMsgLenOffset:]))
		if n < ribHeaderMin || off+n > len(rib) {
			return nil, fmt.Errorf("routing table message of %d bytes at %d does not fit", n, off)
		}
		flags := binary.NativeEndian.Uint32(rib[off+ribFlagsOffset:])
		parent := binary.NativeEndian.Uint32(rib[off+ribParentFlagsStart:])
		clone := flags&syscall.RTF_WASCLONED != 0 && parent&syscall.RTF_PRCLONING != 0
		if !clone {
			kept += copy(rib[kept:], rib[off:off+n])
		}
		off += n
	}
	return rib[:kept], nil
}

// ReadRoutes lets snapshotRoutes read the table in process instead of running
// netstat. The caller falls back to netstat when it fails.
func (r *execRunner) ReadRoutes(context.Context) ([]RouteEntry, error) {
	return readRoutes()
}

// interfaceNames maps interface indexes to names.
func interfaceNames() map[int]string {
	ifaces, err := net.Interfaces()
	if err != nil {
		return nil
	}
	names := make(map[int]string, len(ifaces))
	for _, ifc := range ifaces {
		names[ifc.Index] = ifc.Name
	}
	return names
}

// ribEntries converts routing messages into rows, in table order. A row netstat
// would print without an interface or gateway has no fields to read and is
// skipped, as parseRouteTable skips it.
func ribEntries(msgs []xroute.Message, names func() map[int]string) []RouteEntry {
	byIndex := names()
	entries := make([]RouteEntry, 0, len(msgs))
	for _, msg := range msgs {
		m, ok := msg.(*xroute.RouteMessage)
		if !ok {
			continue
		}
		if e, ok := ribEntry(m, byIndex); ok {
			entries = append(entries, e)
		}
	}
	return entries
}

func ribEntry(m *xroute.RouteMessage, names map[int]string) (RouteEntry, bool) {
	if len(m.Addrs) <= syscall.RTAX_NETMASK {
		return RouteEntry{}, false
	}
	dest, ok := ribDestination(m.Addrs[syscall.RTAX_DST], m.Addrs[syscall.RTAX_NETMASK], m.Flags&syscall.RTF_HOST != 0)
	gateway := ribGateway(m.Addrs[syscall.RTAX_GATEWAY])
	netif := names[m.Index]
	if !ok || gateway == "" || netif == "" {
		return RouteEntry{}, false
	}
	return RouteEntry{Destination: dest, Gateway: gateway, Flags: ribFlags(m.Flags), Interface: netif}, true
}

// Route flag letters in the order netstat prints them (its route.c table);
// syscall lacks the newer flags, whose values come from xnu's net/route.h.
const (
	rtfProxy  = 0x8000000
	rtfRouter = 0x10000000
	rtfGlobal = 0x40000000
)

var ribFlagLetters = []struct {
	mask   int
	letter byte
}{
	{syscall.RTF_UP, 'U'}, {syscall.RTF_GATEWAY, 'G'}, {syscall.RTF_HOST, 'H'}, {syscall.RTF_REJECT, 'R'},
	{syscall.RTF_DYNAMIC, 'D'}, {syscall.RTF_MODIFIED, 'M'}, {syscall.RTF_MULTICAST, 'm'}, {syscall.RTF_DONE, 'd'},
	{syscall.RTF_CLONING, 'C'}, {syscall.RTF_XRESOLVE, 'X'}, {syscall.RTF_LLINFO, 'L'}, {syscall.RTF_STATIC, 'S'},
	{syscall.RTF_BLACKHOLE, 'B'}, {syscall.RTF_PROTO3, '3'}, {syscall.RTF_PROTO2, '2'}, {syscall.RTF_PROTO1, '1'},
	{syscall.RTF_PRCLONING, 'c'}, {syscall.RTF_WASCLONED, 'W'}, {syscall.RTF_BROADCAST, 'b'}, {rtfProxy, 'Y'}, {syscall.RTF_IFSCOPE, 'I'},
	{syscall.RTF_IFREF, 'i'}, {rtfRouter, 'r'}, {rtfGlobal, 'g'},
}

// ribFlags spells a route's flags the way netstat's Flags column does.
func ribFlags(flags int) string {
	var b []byte
	for _, f := range ribFlagLetters {
		if flags&f.mask != 0 {
			b = append(b, f.letter)
		}
	}
	return string(b)
}

// ribDestination spells a destination the way netstat's Destination column
// does: "default", a host's full address, or a network written with its class's
// octets and "/bits" unless the mask is the one its class implies ("10",
// "169.254", "192.168.7", "0/1", "128.0/1", "224.0.0/4", "192.168.138/23").
func ribDestination(dst, mask xroute.Addr, host bool) (string, bool) {
	d, ok := dst.(*xroute.Inet4Addr)
	if !ok {
		return "", false
	}
	in := binary.BigEndian.Uint32(d.IP[:])
	if host {
		return net.IP(d.IP[:]).String(), true
	}
	var m uint32
	if mask != nil {
		mk, ok := mask.(*xroute.Inet4Addr)
		if !ok {
			return "", false
		}
		m = binary.BigEndian.Uint32(mk.IP[:])
	}
	if in == 0 && m == 0 {
		return "default", true
	}

	out := netstatOctets(in)
	if m == 0 || m == classfulMask(in) {
		return out, true
	}
	if ones := bits.LeadingZeros32(^m); ones == bits.OnesCount32(m) {
		return out + "/" + strconv.Itoa(ones), true
	}
	return out + " & 0x" + strconv.FormatUint(uint64(m), 16), true
}

// netstatOctets writes a network address with as many octets as its class has
// network bits (one for class A, two for B, three for C, D and E), and more
// when a later octet is not zero.
func netstatOctets(in uint32) string {
	n := 3
	switch {
	case in>>31 == 0:
		n = 1
	case in>>30 == 0b10:
		n = 2
	}
	for last := 4; last > n; last-- {
		if in>>(32-8*last)&0xff != 0 {
			n = last
			break
		}
	}
	parts := make([]string, n)
	for i := range n {
		parts[i] = strconv.Itoa(int(in >> (24 - 8*i) & 0xff))
	}
	return strings.Join(parts, ".")
}

// classfulMask is the netmask the address's class implies; class D and E have
// none, so their routes always print the length.
func classfulMask(in uint32) uint32 {
	switch {
	case in>>31 == 0:
		return 0xff000000
	case in>>30 == 0b10:
		return 0xffff0000
	case in>>29 == 0b110:
		return 0xffffff00
	}
	return 0
}

// ribGateway spells a gateway the way netstat's Gateway column does: an IPv4
// address; "link#N" for a link-level address with no name or hardware address;
// otherwise the interface name and hardware address joined with a colon, each
// hardware address byte in hex without leading zeros.
func ribGateway(gw xroute.Addr) string {
	switch g := gw.(type) {
	case *xroute.Inet4Addr:
		return net.IP(g.IP[:]).String()
	case *xroute.LinkAddr:
		if g.Name == "" && len(g.Addr) == 0 {
			return "link#" + strconv.Itoa(g.Index)
		}
		var b strings.Builder
		b.WriteString(g.Name)
		if g.Name != "" && len(g.Addr) > 0 {
			b.WriteByte(':')
		}
		for i, octet := range g.Addr {
			if i > 0 {
				b.WriteByte(':')
			}
			b.WriteString(strconv.FormatUint(uint64(octet), 16))
		}
		return b.String()
	}
	return ""
}
